    sessionId: '',
    credsLoaded: false,
    keysLoaded: 0,
    keysWritten: 0,
    bulkWriteDuration: 0,
    keyFetchDuration: 0,
    reconnectCount: 0,
    sessionRestoreSuccess: false,
