let categoryWriteCount: Record<string, number> = {}
let categoryKeyCount: Record<string, number> = {}
let appStateSyncWrites = 0
let appStateVersionWrites = 0
let senderKeyWrites = 0
let sessionWrites = 0

let encryptionKeyMismatchWarnings = 0
let encryptionKeyAutoGenerated = false

let orphanPreKeys = 0
let orphanSenderKeys = 0
let orphanSessions = 0

